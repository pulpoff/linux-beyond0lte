#!/bin/sh
# Builds s10e_dp_audio.ko against a configured kernel build directory, KBUILD: the overlay first
# (dp-audio.dtso -> dp-audio-dtbo.h), then the module.
set -e
cd "$(dirname "$0")"
dtc -@ -q -I dts -O dtb -o dp-audio.dtbo dp-audio.dtso
# The local fixups stay, the symbols go: U-Boot's DT has none, and an overlay with them is refused
fdtput -r dp-audio.dtbo /__symbols__
# libfdt wants the blob 8-byte aligned
{
	echo '/* generated by build.sh from dp-audio.dtso */'
	xxd -i -n dp_audio_dtbo dp-audio.dtbo |
		sed -e 's/^unsigned char \(.*\)\[\]/static const unsigned char \1[] __aligned(8)/' \
		    -e 's/^unsigned int/static const unsigned int/'
} > dp-audio-dtbo.h
make -C "${KBUILD:?set KBUILD to the kernel build directory}" ARCH=arm64 LLVM=1 M="$PWD" modules
